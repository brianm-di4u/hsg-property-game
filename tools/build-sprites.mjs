#!/usr/bin/env node
// Packs the Blender piece renders (art-src/blender/renders/pieces/*.png + pieces.json) into one sprite
// atlas: assets/pieces.webp and src/js/sprites-data.js (frame rects and foot anchors, inlined into the
// game). Each render is trimmed to its visible pixels first. Also writes a review sheet,
// art-src/pieces-sheet.png, with every piece over its shadow on board-coloured stock.
//   node tools/build-sprites.mjs [--scale 1]
// Uses the harness's Playwright Chromium; no image libraries.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.resolve(GAME, 'shared', 'test-harness', 'package.json'));
const { chromium } = require('playwright');
const SRC = path.join(GAME, 'art-src', 'blender', 'renders', 'pieces');
const meta = JSON.parse(fs.readFileSync(path.join(SRC, 'pieces.json'), 'utf8'));
const names = Object.keys(meta).sort();
const files = [];
for (const n of names) {
  files.push({ key: n, file: path.join(SRC, n + '.png') });
  if (fs.existsSync(path.join(SRC, n + '-shadow.png'))) files.push({ key: n + '-shadow', file: path.join(SRC, n + '-shadow.png'), shadowOf: n });
}
const data = files.map((f) => ({ key: f.key, url: 'data:image/png;base64,' + fs.readFileSync(f.file).toString('base64') }));

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<!doctype html><body style="margin:0"></body>');
const res = await page.evaluate(async ({ data, meta }) => {
  const imgs = {};
  for (const d of data) { const im = new Image(); im.src = d.url; await im.decode(); imgs[d.key] = im; }
  // trim each image to its alpha bounds (shadows: alpha > 3)
  const trims = {};
  for (const [k, im] of Object.entries(imgs)) {
    const c = document.createElement('canvas'); c.width = im.width; c.height = im.height;
    const g = c.getContext('2d'); g.drawImage(im, 0, 0);
    const p = g.getImageData(0, 0, c.width, c.height).data;
    let x0 = c.width, y0 = c.height, x1 = -1, y1 = -1;
    for (let y = 0; y < c.height; y++) for (let x = 0; x < c.width; x++) if (p[(y * c.width + x) * 4 + 3] > 3) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
    if (x1 < 0) { x0 = y0 = 0; x1 = y1 = 0; }
    x0 = Math.max(0, x0 - 1); y0 = Math.max(0, y0 - 1); x1 = Math.min(c.width - 1, x1 + 1); y1 = Math.min(c.height - 1, y1 + 1);
    trims[k] = { x0, y0, w: x1 - x0 + 1, h: y1 - y0 + 1 };
  }
  // shelf pack, tallest first
  const keys = Object.keys(trims).sort((a, b) => trims[b].h - trims[a].h);
  const W = 1024; let x = 0, y = 0, rowH = 0; const frames = {};
  for (const k of keys) {
    const t = trims[k];
    if (x + t.w + 2 > W) { x = 0; y += rowH + 2; rowH = 0; }
    frames[k] = { x, y, w: t.w, h: t.h }; x += t.w + 2; rowH = Math.max(rowH, t.h);
  }
  const H = y + rowH;
  const atlas = document.createElement('canvas'); atlas.width = W; atlas.height = H;
  const ag = atlas.getContext('2d');
  for (const k of keys) { const t = trims[k], f = frames[k]; ag.drawImage(imgs[k], t.x0, t.y0, t.w, t.h, f.x, f.y, f.w, f.h); }
  // anchors: foot point relative to the trimmed frame
  const out = {};
  for (const k of keys) {
    const base = k.endsWith('-shadow') ? k.slice(0, -7) : k, m = meta[base], t = trims[k], f = frames[k];
    out[k] = [f.x, f.y, f.w, f.h, +(m.footX - t.x0).toFixed(1), +(m.footY - t.y0).toFixed(1), m.pxPerUnit];
  }
  // review sheet: piece over shadow on cream stock
  const bases = Object.keys(meta).sort();
  const cell = 210, cols = 6, rows = Math.ceil(bases.length / cols);
  const sh = document.createElement('canvas'); sh.width = cols * cell; sh.height = rows * cell;
  const sg = sh.getContext('2d'); sg.fillStyle = '#EFE4CB'; sg.fillRect(0, 0, sh.width, sh.height);
  bases.forEach((b, i) => {
    const cx = (i % cols) * cell + cell / 2, cy = Math.floor(i / cols) * cell + cell * 0.62;
    for (const k of [b + '-shadow', b]) {
      if (!out[k]) continue; const [fx, fy, fw, fh, ax, ay] = out[k];
      sg.drawImage(atlas, fx, fy, fw, fh, cx - ax, cy - ay, fw, fh);
    }
    sg.fillStyle = '#333'; sg.font = '13px sans-serif'; sg.fillText(b, (i % cols) * cell + 6, Math.floor(i / cols) * cell + 16);
  });
  return { atlas: atlas.toDataURL('image/webp', 0.9).split(',')[1], sheet: sh.toDataURL('image/png').split(',')[1], frames: out, W, H };
}, { data, meta });
await browser.close();
fs.mkdirSync(path.join(GAME, 'assets'), { recursive: true });
fs.writeFileSync(path.join(GAME, 'assets', 'pieces.webp'), Buffer.from(res.atlas, 'base64'));
fs.writeFileSync(path.join(GAME, 'art-src', 'pieces-sheet.png'), Buffer.from(res.sheet, 'base64'));
const js = `// GENERATED by tools/build-sprites.mjs from the Blender renders (art-src/blender/pieces.py). Do not edit.\n` +
  `// Each frame: [x, y, w, h, footX, footY, pxPerUnit] in assets/pieces.webp (${res.W}x${res.H}).\n` +
  `export const SPRITES = ${JSON.stringify(res.frames)};\n`;
fs.writeFileSync(path.join(GAME, 'src', 'js', 'sprites-data.js'), js);
console.log(`atlas ${res.W}x${res.H}, ${Object.keys(res.frames).length} frames, ${(fs.statSync(path.join(GAME, 'assets', 'pieces.webp')).size / 1024).toFixed(1)} KB`);
