#!/usr/bin/env node
// Inlines the vendored OFL fonts (vendor/fonts/*.woff2, from npm @fontsource) into assets/fonts.css as data URIs.
// Chrome blocks @font-face loads from file:// pages, so the fonts travel inside a stylesheet that a plain
// <link rel="stylesheet"> loads from file:// and http alike.
//   node tools/build-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(GAME, 'vendor', 'fonts');
const FACES = [
  // board labels, UI headings, buttons: condensed, fits full lot names
  ['Barlow Condensed', 600, 'normal', 'barlow-condensed-latin-600-normal.woff2'],
  ['Barlow Condensed', 700, 'normal', 'barlow-condensed-latin-700-normal.woff2'],
  // title, prices, deed names: 1930s board-game slab
  ['Alfa Slab One', 400, 'normal', 'alfa-slab-one-latin-400-normal.woff2'],
  // fact text and newspaper body
  ['Libre Caslon Text', 400, 'normal', 'libre-caslon-text-latin-400-normal.woff2'],
  ['Libre Caslon Text', 400, 'italic', 'libre-caslon-text-latin-400-italic.woff2'],
  // newspaper mastheads and Headline titles
  ['Abril Fatface', 400, 'normal', 'abril-fatface-latin-400-normal.woff2'],
];
let css = '/* Generated by tools/build-fonts.mjs from vendor/fonts (SIL Open Font License 1.1). Do not edit. */\n';
for (const [family, weight, style, file] of FACES) {
  const b64 = fs.readFileSync(path.join(SRC, file)).toString('base64');
  css += `@font-face{font-family:"${family}";font-style:${style};font-weight:${weight};font-display:block;` +
    `src:url(data:font/woff2;base64,${b64}) format("woff2")}\n`;
}
fs.mkdirSync(path.join(GAME, 'assets'), { recursive: true });
fs.writeFileSync(path.join(GAME, 'assets', 'fonts.css'), css);
console.log('assets/fonts.css', (css.length / 1024).toFixed(1), 'KB');
