#!/usr/bin/env node
// Tree-shakes the vendored three.js (vendor/three, r186, MIT) down to the classes the 3D table uses and writes
// src/js/three-lib.js, a plain module the shared inliner can bundle (no imports, one `export const THREE`).
//   cd tools/dev && npm install   (once: esbuild, build-time only)
//   node tools/build-three.mjs
// Add a name to NAMES when board3d.js starts using another three.js export.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const game = path.join(here, '..');
const require = createRequire(path.join(here, 'dev', 'package.json'));
const esbuild = require('esbuild');
const NAMES = [
  'WebGLRenderer', 'Scene', 'PerspectiveCamera', 'Group', 'Object3D', 'Mesh', 'InstancedMesh',
  'BufferGeometry', 'BufferAttribute', 'Float32BufferAttribute', 'PlaneGeometry', 'BoxGeometry', 'CylinderGeometry', 'SphereGeometry',
  'MeshStandardMaterial', 'MeshBasicMaterial', 'MeshPhysicalMaterial', 'ShadowMaterial',
  'CanvasTexture', 'Texture', 'HemisphereLight', 'DirectionalLight', 'AmbientLight', 'SpotLight',
  'Color', 'Vector2', 'Vector3', 'Matrix4', 'Quaternion', 'Euler', 'MathUtils', 'Raycaster', 'Plane', 'Box3',
  'SRGBColorSpace', 'NoColorSpace', 'ACESFilmicToneMapping', 'NeutralToneMapping', 'AgXToneMapping', 'PCFSoftShadowMap', 'PCFShadowMap',
  'PMREMGenerator', 'BackSide', 'RepeatWrapping', 'ClampToEdgeWrapping', 'LinearFilter', 'LinearMipmapLinearFilter', 'DoubleSide', 'FrontSide', 'REVISION',
];
const entry = `export { ${NAMES.join(', ')} } from ${JSON.stringify(path.join(game, 'vendor', 'three', 'three.module.js').split(path.sep).join('/'))};`;
const res = await esbuild.build({
  stdin: { contents: entry, resolveDir: game, loader: 'js' },
  bundle: true, minify: true, format: 'iife', globalName: '__THREE', write: false, target: 'es2020', legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
});
let code = res.outputFiles[0].text.trim();
code = code.replace(/^(\s*)(import|export)\b/gm, '$1;$2');
const out = `// GENERATED by tools/build-three.mjs from vendor/three (three.js r186, MIT, Copyright 2010-2026 Three.js Authors).\n` +
  `// Tree-shaken and minified with esbuild. Do not edit by hand.\n${code}\nexport const THREE = __THREE;\n`;
fs.writeFileSync(path.join(game, 'src', 'js', 'three-lib.js'), out);
console.log(`three-lib.js ${(out.length / 1024).toFixed(1)} KB (${NAMES.length} exports)`);
